"""
Instagram privacy and poison module.
Applies aggressive image perturbation, metadata stripping, and phantom account decoys.
"""

import logging
from typing import Dict, List, Any, Union

from . import PlatformPoisonModule
from ..egress_guard import ContentType, PrivacyStrength
from ..perturbation import PerturbationEngine

logger = logging.getLogger(__name__)


class InstagramPoisonModule(PlatformPoisonModule):
    """
    Instagram-specific defense module.
    Due to Instagram's heavy image compression, AGGRESSIVE perturbation is applied.
    Audio perturbation is bypassed for Reels because lossy AAC/Opus codec destroys it.
    """

    def __init__(self):
        super().__init__("instagram")
        self.perturbation_engine = PerturbationEngine(PrivacyStrength.AGGRESSIVE)

    def supported_features(self) -> Dict[str, Any]:
        return {
            "metadata_stripping": True,
            "image_perturbation": "AGGRESSIVE",
            "audio_perturbation": False,  # Bypassed: Lossy Reels codec destroys psychoacoustic noise
            "video_perturbation": "Offline only",
            "stylometric_shift": False,  # Hard Rule: User's words are never altered
            "phantom_activity": "Decoy follows",
            "tracker_pollution": "Profile browse",
        }

    async def apply_egress_filter(
        self,
        content: Union[str, bytes],
        content_type: ContentType,
        is_phantom: bool = False,
        **kwargs
    ) -> Union[str, bytes]:
        """Apply Instagram egress filtering."""
        if content_type == ContentType.TEXT:
            if not isinstance(content, str):
                return content
            # Hard Rule: Only shift style if content is auto-generated by a phantom account
            if is_phantom:
                return await self.style_guard.apply_noise(content)
            return content

        elif content_type == ContentType.IMAGE:
            if not isinstance(content, bytes):
                return content
            stripped = await self.metadata_stripper.strip_image_metadata(content)
            return await self.perturbation_engine.perturb_image(stripped, destination="instagram")

        elif content_type == ContentType.AUDIO:
            if not isinstance(content, bytes):
                return content
            # Metadata stripped, but audio perturbation bypassed (lossy reels)
            return await self.metadata_stripper.strip_audio_metadata(content)

        elif content_type in (ContentType.VIDEO, ContentType.RAW):
            if not isinstance(content, bytes):
                return content
            return await self.perturbation_engine.perturb_video(content, destination="instagram")

        return content

    def get_phantom_actions(self) -> List[Dict[str, Any]]:
        """Scheduled phantom activities (decoy browsing and following)."""
        return [
            {"action": "browse_explore", "duration_sec": 45, "persona": "tech_enthusiast"},
            {"action": "decoy_follow", "target_category": "gardening", "count": 2},
            {"action": "view_stories", "categories": ["wildlife", "astronomy"]},
        ]
